import React, { useState } from 'react';
import { useAuth } from '../../context/AuthContext';
import { Icon, FCAILogo } from '../../components/icons/Icon';
import { fakeApi } from '../../services/fakeApi';

export const FirstLogin: React.FC<{ onComplete?: () => void }> = ({ onComplete }) => {
  const { switchRole, showToast } = useAuth();
  const [tempPassword, setTempPassword] = useState('Tmp#48213');
  const [newPassword, setNewPassword] = useState('');
  const [confirmPassword, setConfirmPassword] = useState('');
  const [isSuccess, setIsSuccess] = useState(false);
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // Validation rules
  const rules = [
    { label: 'At least 8 characters', valid: newPassword.length >= 8 },
    { label: 'One uppercase letter', valid: /[A-Z]/.test(newPassword) },
    { label: 'One number', valid: /[0-9]/.test(newPassword) },
    { label: 'One special character (!@#$%^&*)', valid: /[!@#$%^&*(),.?":{}|<>]/.test(newPassword) },
    { label: 'Passwords match', valid: newPassword !== '' && newPassword === confirmPassword }
  ];

  const allValid = rules.every(r => r.valid);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!allValid) {
      setError('Please satisfy all password security requirements.');
      return;
    }

    setIsLoading(true);
    setError(null);
    try {
      await fakeApi.updatePassword(tempPassword, newPassword);
      setIsSuccess(true);
      showToast('Password Changed', 'Your temporary password has been successfully replaced.');
      setTimeout(() => {
        if (onComplete) {
          onComplete();
        } else {
          switchRole('student');
          window.location.hash = '#/student/dashboard';
        }
      }, 1500);
    } catch (err: any) {
      setError(err?.message || 'Failed to update password.');
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <div className="auth">
      <aside className="auth-art" aria-hidden="false">
        <div className="row" style={{ position: 'relative', zIndex: 2 }}>
          <FCAILogo size={46} />
          <div>
            <b style={{ fontSize: '16px', display: 'block', color: 'var(--text)' }}>
              FCAI · Beni Suef University
            </b>
            <span style={{ fontSize: '12.5px', color: 'var(--text-muted)', fontWeight: 500 }}>
              Faculty of Computers &amp; Artificial Intelligence
            </span>
          </div>
        </div>
        <div style={{ position: 'relative', zIndex: 2, maxWidth: '440px' }}>
          <span className="hero-chip mb-4">
            <Icon name="key" size="sm" /> Mandatory Security Initialization
          </span>
          <h2 style={{ fontSize: '30px', fontWeight: 750, color: '#fff', marginTop: '12px' }}>
            Let's secure your new account.
          </h2>
          <p style={{ color: '#c4dbf3', marginTop: '10px', fontSize: '15px' }}>
            Your account was generated by the College with an initial temporary password. In accordance with university data security standards, you must replace it before accessing academic services.
          </p>
        </div>
      </aside>

      <div className="auth-form">
        <div className="auth-card">
          {isSuccess ? (
            <div className="state" style={{ padding: 0 }}>
              <div className="state-art success">
                <Icon name="shieldCheck" size="xl" />
              </div>
              <h3 style={{ fontSize: '22px' }}>Password Successfully Updated</h3>
              <p>Your institutional credentials have been secured. Redirecting you to your Student Dashboard…</p>
              <div className="spinner mt-3" />
            </div>
          ) : (
            <>
              <span className="badge b-warning mb-4">First-Time Sign-In</span>
              <h1 style={{ fontSize: '26px', fontWeight: 750, letterSpacing: '-.02em', marginTop: '12px' }}>
                Replace your temporary password
              </h1>
              <p className="muted mt-2 mb-6">
                Temporary passwords issued by Student Affairs expire upon first login. Choose a strong personal password.
              </p>

              {error && (
                <div className="alert alert-danger mb-4">
                  <Icon name="alertCircle" />
                  <div>
                    <b>Error updating password</b>
                    <p>{error}</p>
                  </div>
                </div>
              )}

              <form className="col gap-4" onSubmit={handleSubmit}>
                <div className="field">
                  <label className="label">Current Temporary Password</label>
                  <input
                    className="input"
                    type="password"
                    value={tempPassword}
                    onChange={e => setTempPassword(e.target.value)}
                    required
                  />
                </div>

                <div className="field">
                  <label className="label">New Personal Password</label>
                  <input
                    className="input"
                    type="password"
                    placeholder="Enter new password"
                    value={newPassword}
                    onChange={e => setNewPassword(e.target.value)}
                    required
                  />
                </div>

                <div className="field">
                  <label className="label">Confirm New Password</label>
                  <input
                    className="input"
                    type="password"
                    placeholder="Re-type new password"
                    value={confirmPassword}
                    onChange={e => setConfirmPassword(e.target.value)}
                    required
                  />
                </div>

                {/* Password strength checklist */}
                <div className="info-tile">
                  <small className="fw-6" style={{ color: 'var(--text)' }}>Password Security Requirements:</small>
                  <div className="pw-rules mt-2">
                    {rules.map((rule, idx) => (
                      <div key={idx} className={rule.valid ? 'ok' : ''}>
                        <Icon name={rule.valid ? 'checkCircle' : 'alertCircle'} size="sm" />
                        {rule.label}
                      </div>
                    ))}
                  </div>
                </div>

                <button
                  className="btn btn-primary btn-lg btn-block mt-2"
                  type="submit"
                  disabled={isLoading || !allValid}
                >
                  {isLoading ? 'Updating…' : 'Save New Password & Continue'}
                </button>
              </form>
            </>
          )}
        </div>
      </div>
    </div>
  );
};
